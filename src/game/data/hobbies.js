// シニア向けの動画やnoteでよく紹介される趣味を、参考情報（tip）つきで選べるようにする。
// tags: exercise=体を動かす / social=人と関わる / creative=作る・表現する
// 効果の根拠：JAGES（約9万人を約3年追跡）では、趣味・スポーツ・ボランティア・就労などに参加する人ほど
// 要介護認定のリスクが低く、参加の種類が多いほど低い傾向だった（健康な人ほど参加しやすいという逆の因果も議論されている）。

const JAGES_NOTE = '約9万人の高齢者を追跡したJAGES（日本老年学的評価研究）では、趣味やスポーツ、ボランティアなどに参加している人ほど、その後に要介護認定を受けるリスクが低く、参加の種類が多いほど低い傾向でした（健康な人ほど参加しやすい、という逆向きの関係も指摘されています）。'

function hobbyEvent({ chapter, act, imageId, title, intro, hobbies }) {
  return {
    chapter, act, imageId, title, hobbyChoice: true,
    body: () => [intro, JAGES_NOTE],
    choices: () => [
      ...hobbies.map((h) => ({
        id: h.id,
        label: h.label,
        detail: h.detail,
        tip: h.tip,
        requiresHealth: h.requiresHealth,
        effect: { ...h.effect, hobby: { name: h.name, tags: h.tags } },
        fragment: h.fragment,
      })),
      { id: `${imageId}_none`, label: '今回は、何も始めない', detail: '変化なし' },
    ],
  }
}

