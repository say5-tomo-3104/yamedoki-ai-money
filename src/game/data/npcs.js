const REAL_MULT = { 60: 0.81, 65: 1.0, 70: 1.324, 75: 1.641 }
const HARUKA_DEATH_AGE = 79

// プレイヤーが選ばなかった年齢に3人を割り振る（SPEC.md 第5章）
export function assignNpcAges(playerAge) {
  return {
    kenta: playerAge === 60 ? 65 : 60,
    seiichi: playerAge === 70 ? 65 : 70,
    haruka: playerAge === 75 ? 65 : 75,
  }
}

function harukaDies(id, pAge, fate) {
  return id === 'haruka' && pAge === 75 && !fate.harukaAlive
}

export function npcPresent(id, fate, pAge, age) {
  return !(harukaDies(id, pAge, fate) && age >= HARUKA_DEATH_AGE)
}

export function npcMonthlyNet(id, pAge) {
  return Math.round(NPC_DATA[id].net65 * REAL_MULT[pAge] * 10) / 10
}

export function npcCumulative(id, pAge, age, fate) {
  const until = harukaDies(id, pAge, fate) ? Math.min(age, HARUKA_DEATH_AGE) : age
  return Math.max(0, until - pAge) * 12 * npcMonthlyNet(id, pAge)
}

// 思い出スコアの推移（同窓会の年齢ごとの値）
const HEART = {
  kenta: { 60: [50, 110, 140, 160], 65: [50, 90, 120, 140] },
  seiichi: {
    70: { wall: [50, 40, 55, 70], win: [50, 40, 110, 135] },
    65: { wall: [50, 65, 70, 85], win: [50, 65, 95, 115] },
  },
  haruka: { 75: { alive: [50, 60, 65, 120], dead: [50, 60, 65, 70] }, 65: [50, 70, 90, 110] },
}

export function npcHeart(id, pAge, age, fate) {
  let series
  if (id === 'kenta') series = HEART.kenta[pAge]
  else if (id === 'seiichi') series = HEART.seiichi[pAge][fate.seiichiWall ? 'wall' : 'win']
  else series = pAge === 75 ? HEART.haruka[75][fate.harukaAlive ? 'alive' : 'dead'] : HEART.haruka[65]
  const points = [[50, series[0]], [62, series[1]], [73, series[2]], [82, series[3]], [85, series[3] + 8]]
  if (harukaDies(id, pAge, fate)) points[4] = [85, series[3]]
  for (let i = 1; i < points.length; i++) {
    const [a1, v1] = points[i]
    const [a0, v0] = points[i - 1]
    if (age <= a1) return v0 + ((v1 - v0) * (age - a0)) / (a1 - a0)
  }
  return points[points.length - 1][1]
}

